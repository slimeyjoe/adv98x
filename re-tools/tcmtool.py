"""tcmtool - listings and emulation runs for NOVA's machine-code plug-ins (*.TCM).

  tcmtool.py list [--names docs/re/listing/tcm-names.tsv]
                  [--dir resources/original/pc98/A] [--out resources/derived/listing]
      Write one annotated listing per plug-in (tcm-<FILE>.lst) with dis16's
      recursive descent.  The names file has lines
          FILE<TAB>OFFSET<TAB>name<TAB>comment
      (FILE without extension, OFFSET hex).  Every named address whose comment
      does not start with "data" is a code entry; "data" names are used to
      annotate operands and are listed (with a hex dump while inside the file)
      at the end.  Listings are the game's code: keep them out of docs/.

  tcmtool.py run FILE.TCM LOAD ARG... [--keys K,K,...] [--palette W,W,...]
                 [--mailbox W,W,...] [--pattern] [--quiet-ports]
      Run the plug-in under unicorn the way `exec-mem LOAD ARG...` calls it
      (docs/re/interpreter.md §6) with AdvBIOS, DOS and the hardware stubbed,
      and print a log of every INT call and port access.
        ARG        decimal number, or a string in double quotes (as in a script;
                   give Shift-JIS as \\xNN escapes or type the text - it is
                   encoded as cp932)
        --keys     key words (hex AHAL: scan code, character) returned by
                   INT 18h AH=00h, e.g. 1E61,1C0D
        --palette  16 hex words 0GRB: AdvBIOS palette buffer at entry
        --mailbox  16 hex words: buffer returned by INT F3h AH=FFh
        --pattern  fill both VRAM pages with a position-dependent pattern and
                   print a checksum of each page before and after
      Several ARG lists can be run one after the other in the same loaded
      image by separating them with a bare "/" (state inside the image and
      the DOS heap persist, as in the game).

VSYNC model: the VSYNC interrupt (INT 0Ah) is delivered once every 20000
instructions while interrupts are enabled, IRQ2 is unmasked (port 02h bit 2
clear) and the interrupt was requested by a write to port 64h; the VSYNC bit
of port A0h (bit 5) toggles every 300 reads.  The log counts frames, it does
not measure time.
"""
import argparse
import os
import re
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                # the engine's
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'source', 'tools'))
import gamedir  # noqa: E402


# ---------------------------------------------------------------- listings
def load_tcm_names(path):
    """-> {FILE: {off: (name, comment)}}"""
    res = {}
    for line in open(path, encoding='utf-8'):
        line = line.rstrip('\n')
        if not line or line.startswith('#'):
            continue
        f = line.split('\t')
        res.setdefault(f[0].upper(), {})[int(f[1], 16)] = (
            f[2] if len(f) > 2 else '', f[3] if len(f) > 3 else '')
    return res


_HEX = re.compile(r'0x[0-9a-f]+')
_FLOW = ('call', 'jmp', 'loop', 'jcxz')


def cmd_list(a):
    import dis16
    allnames = load_tcm_names(a.names)
    a.dir = a.dir or gamedir.original(None, 'pc98', 'A')
    a.out = a.out or gamedir.derived(None, 'listing')
    os.makedirs(a.out, exist_ok=True)
    for fname, names in sorted(allnames.items()):
        src = os.path.join(a.dir, fname + '.TCM')
        img = dis16.Image.load_raw(src)
        an = dis16.Analysis(img)
        an.explore(0, 0)
        for off, (nm, cm) in names.items():
            if not cm.startswith('data') and off < len(img.data):
                an.explore(0, off)
        dst = os.path.join(a.out, 'tcm-%s.lst' % fname)
        with open(dst, 'w', encoding='utf-8') as out:
            out.write('; %s.TCM  %d bytes  (generated by tcmtool.py list)\n'
                      % (fname, len(img.data)))
            prev = None
            for adr in sorted(an.insns):
                seg, size, mn, ops = an.insns[adr]
                if prev is not None and adr != prev:
                    out.write('\n')
                if adr in names or adr in an.funcs:
                    nm, cm = names.get(adr, ('sub_%04X' % adr, ''))
                    out.write('\n; ---- %s  %s\n' % (nm, cm))
                    xr = sorted(an.xrefs.get(adr, ()))
                    if xr:
                        out.write(';      xrefs: %s\n' % ' '.join(
                            '%04X' % x for x in xr[:14]))
                elif adr in an.labels:
                    out.write('  loc_%04X:\n' % adr)
                note = []
                for m in _HEX.finditer(ops):
                    v = int(m.group(), 16)
                    if v not in names:
                        continue
                    in_mem = '[' in ops[:m.start()] and ']' in ops[m.end():]
                    if in_mem or mn.startswith('j') or mn in _FLOW or v >= 0x100:
                        note.append(names[v][0])
                out.write('%04X  %-16s %-7s %s%s\n' % (
                    adr, img.data[adr:adr + size].hex(), mn, ops,
                    ('   ; ' + ', '.join(note)) if note else ''))
                prev = adr + size
            out.write('\n; ---- data\n')
            offs = sorted(o for o, (n, c) in names.items()
                          if c.startswith('data'))
            for i, off in enumerate(offs):
                nm, cm = names[off]
                end = offs[i + 1] if i + 1 < len(offs) else off + 16
                end = min(end, off + 48, len(img.data))
                dump = img.data[off:end].hex(' ') if off < len(img.data) \
                    else '(beyond the end of the file)'
                out.write('%04X  %-20s %s\n        %s\n' % (off, nm, cm, dump))
        print('wrote', dst)


# --------------------------------------------------------------- emulation
ISEG = 0x3000       # "interpreter" segment (DS = ES = CS of the near call)
SSEG = 0x2000
RET_OFF = 0xFF00    # near return address
ARG_OFF = 0xDA73    # exec-mem argument block (as in NV.OVL)
STR_OFF = 0xE000    # where string arguments are put
BIOS_SEG = 0x0290   # segment reported for the INT F3h AH=FFh mailbox
MAILBOX = (BIOS_SEG, 0x045C)
GPCBUF = (0x04E9, 0x0454)
HEAP_LO, HEAP_HI = 0x5000, 0x9000   # DOS heap handed out by INT 21h AH=48h
PLANES = (0xA800, 0xB000, 0xB800, 0xE000)


class Machine:
    def __init__(self, a):
        import unicorn
        from unicorn import x86_const as X
        self.X = X
        self.uc = unicorn.Uc(unicorn.UC_ARCH_X86, unicorn.UC_MODE_16)
        self.uc.mem_map(0, 0x110000)
        self.a = a
        self.log = []
        self.frame = 0
        self.armed = False
        self.imr = 0xFF
        self.a0_reads = 0
        self.page = 0                      # GDC drawing page (port A6h)
        self.vram = [bytearray(4 * 0x8000), bytearray(4 * 0x8000)]
        self.palette = [0] * 16
        self.brightness = 15
        self.keys = []
        self.heap = {}                     # seg -> paragraphs
        self.heap_next = HEAP_LO
        self.blocked = False
        # stand-ins for the BIOS handlers a plug-in may chain to:
        # INT 0Ah (VSYNC): EOI, iret;  INT 18h: iret
        self.wr(0xF000, 0x0100, bytes.fromhex('50b020e60058cf'))
        self.wr(0xF000, 0x0110, b'\xcf')
        self.wr(0, 0x0A * 4, struct.pack('<HH', 0x0100, 0xF000))
        self.wr(0, 0x18 * 4, struct.pack('<HH', 0x0110, 0xF000))
        self.uc.hook_add(unicorn.UC_HOOK_INTR, self.on_int)
        self.uc.hook_add(unicorn.UC_HOOK_INSN, self.on_in, None, 1, 0,
                         X.UC_X86_INS_IN)
        self.uc.hook_add(unicorn.UC_HOOK_INSN, self.on_out, None, 1, 0,
                         X.UC_X86_INS_OUT)

    # -- helpers
    def r(self, name):
        return self.uc.reg_read(getattr(self.X, 'UC_X86_REG_' + name))

    def w(self, name, v):
        self.uc.reg_write(getattr(self.X, 'UC_X86_REG_' + name), v)

    def rd(self, seg, off, n):
        return bytes(self.uc.mem_read(seg * 16 + off, n))

    def wr(self, seg, off, b):
        self.uc.mem_write(seg * 16 + off, bytes(b))

    def say(self, s):
        self.log.append('[f%03d] %s' % (self.frame, s))

    def carry(self, on):
        f = self.r('EFLAGS')
        self.w('EFLAGS', (f | 1) if on else (f & ~1))

    # -- VRAM paging: the visible planes in memory belong to self.page
    def vram_sync_out(self):
        for i, seg in enumerate(PLANES):
            self.vram[self.page][i * 0x8000:(i + 1) * 0x8000] = \
                self.rd(seg, 0, 0x8000)

    def vram_sync_in(self):
        for i, seg in enumerate(PLANES):
            self.wr(seg, 0, self.vram[self.page][i * 0x8000:(i + 1) * 0x8000])

    def vram_crc(self):
        self.vram_sync_out()
        return ['%08X' % zlib.crc32(bytes(p[:4 * 0x8000])) for p in self.vram]

    # -- ports
    def on_in(self, uc, port, size, user):
        if port == 0xA0:
            self.a0_reads += 1
            phase = (self.a0_reads // 300) % 2
            if self.a0_reads % 300 == 0 and phase:
                self.frame += 1             # VSYNC begins
            return 0x20 if phase else 0x00
        if port == 0x02:
            return self.imr
        if not self.a.quiet_ports:
            self.say('in  %02Xh' % port)
        return 0

    def on_out(self, uc, port, size, value, user):
        if port == 0x64:
            self.armed = True
            return
        if port == 0x02:
            if not self.a.quiet_ports:
                self.say('out 02h,%02Xh  (IMR: VSYNC IRQ2 %s)' % (
                    value, 'masked' if value & 4 else 'enabled'))
            self.imr = value
            return
        if port == 0xA6:
            self.vram_sync_out()
            self.page = value & 1
            self.vram_sync_in()
            self.say('out A6h,%d  (drawing page)' % (value & 0xFF))
            return
        if port == 0xA4:
            self.say('out A4h,%d  (display page)' % (value & 0xFF))
            return
        if port == 0x00 and value == 0x20:
            return                          # EOI
        if not self.a.quiet_ports:
            self.say('out %02Xh,%02Xh' % (port, value & 0xFF))

    # -- interrupts
    def on_int(self, uc, n, user):
        ax, bx, cx, dx = (self.r(x) for x in ('AX', 'BX', 'CX', 'DX'))
        ah, al = ax >> 8, ax & 0xFF
        ds, es, si, di = (self.r(x) for x in ('DS', 'ES', 'SI', 'DI'))
        if n == 0xF3:
            if ah == 0x13:
                pal = list(struct.unpack('<16H', self.rd(ds, si, 32)))
                self.palette = pal
                if al != 0xFF:
                    self.brightness = al
                self.say('F3/13 set palette, brightness %02Xh: %s' % (
                    al, ' '.join('%03X' % p for p in pal)))
            elif ah == 0x14:
                self.wr(es, di, struct.pack('<16H', *self.palette))
                self.w('AX', self.brightness)
                self.say('F3/14 get palette -> %04X:%04X' % (es, di))
            elif ah == 0x15:
                self.palette[al & 15] = bx
                self.say('F3/15 set colour %d = %03X, brightness CL=%02Xh' % (
                    al, bx, cx & 0xFF))
            elif ah == 0x16:
                self.w('BX', self.palette[al & 15])
                self.w('AX', self.brightness)
                self.say('F3/16 get colour %d -> %03X' % (
                    al, self.palette[al & 15]))
            elif ah == 0xFF:
                self.w('ES', MAILBOX[0])
                self.w('BX', MAILBOX[1])
                self.say('F3/FF mailbox pointer -> %04X:%04X' % MAILBOX)
            elif ah == 0x00:
                self.w('ES', GPCBUF[0])
                self.w('BX', GPCBUF[1])
                self.w('CX', 0xF800)
                self.say('F3/00 GPC buffer -> %04X:%04X' % GPCBUF)
            elif ah == 0x01:
                p = struct.unpack('<8H', self.rd(ds, si, 16))
                self.say('F3/01 draw GPC, block: ' +
                         ' '.join('%04X' % x for x in p))
            else:
                self.say('F3/%02X AL=%02X ?' % (ah, al))
        elif n == 0xF6:
            if ah == 0x13:
                self.say('F6/13 bold AL=%d' % al)
            elif ah == 0x04:
                self.w('AX', (ah << 8) | 7)
                self.say('F6/04 get text colour -> 7')
            elif ah == 0x03:
                self.say('F6/03 set text colour %d' % al)
            elif ah == 0x05:
                self.say('F6/05 cursor x=%d y=%d' % (cx, dx))
            elif ah == 0x09:
                try:
                    ch = struct.pack('>H', dx).decode('cp932')
                except UnicodeDecodeError:
                    ch = '?'
                self.say('F6/09 draw char %04X %s' % (dx, ch))
            elif ah == 0x0D:
                self.say('F6/0D fill rect %s colour %d' % (
                    struct.unpack('<4H', self.rd(ds, si, 8)), al))
            else:
                self.say('F6/%02X AL=%02X ?' % (ah, al))
        elif n == 0xF1:
            if ah == 0x00:
                self.w('AX', 0x3600)
                self.w('BX', bx & 0x00FF)
                self.say('F1/00 version -> 3600h')
            elif ah == 0x07:
                self.say('F1/07 wait for input')
            else:
                self.say('F1/%02X ?' % ah)
        elif n == 0xF2:
            if ah == 0x04:
                self.say('F2/04 expect disk DL=%d in drive index AL=%d' % (
                    dx & 0xFF, al))
            elif ah == 0x01:
                name = self.rd(ds, dx, 64).split(b'\0')[0].decode('ascii')
                data = self.rd(es, bx, cx)
                self.w('AX', cx)
                self.carry(False)
                self.say('F2/01 write "%s" %d bytes from %04X:%04X:' % (
                    name, cx, es, bx))
                for i in range(0, min(len(data), 48), 16):
                    self.say('      ' + data[i:i + 16].hex(' '))
                tail = data[48:]
                if tail and tail == tail[:1] * len(tail):
                    self.say('      ... then %d x %02X' % (len(tail), tail[0]))
            elif ah == 0x00:
                name = self.rd(ds, dx, 64).split(b'\0')[0].decode(
                    'ascii', 'replace')
                self.say('F2/00 read "%s" -> %04X:%04X' % (name, es, bx))
            else:
                self.say('F2/%02X ?' % ah)
        elif n == 0x18:
            if ah == 0x01:
                self.w('BX', bx & 0x00FF)       # buffer empty
            elif ah == 0x00:
                if not self.keys:
                    self.say('18/00 read key: no more keys - stopping')
                    self.blocked = True
                    uc.emu_stop()
                    return
                k = self.keys.pop(0)
                self.w('AX', k)
                self.say('18/00 read key -> %04X' % k)
            elif ah in (0x40, 0x41):
                self.say('18/%02X graphics display %s' % (
                    ah, 'on' if ah == 0x40 else 'off'))
            else:
                self.say('18/%02X ?' % ah)
        elif n == 0x21:
            if ah == 0x48:
                if self.heap_next + bx > HEAP_HI or bx == 0xFFFF:
                    self.w('BX', HEAP_HI - self.heap_next)
                    self.w('AX', 8)
                    self.carry(True)
                    self.say('21/48 alloc %04Xh paragraphs -> fails' % bx)
                else:
                    seg = self.heap_next
                    self.heap[seg] = bx
                    self.heap_next += bx + 1
                    self.w('AX', seg)
                    self.carry(False)
                    self.say('21/48 alloc %04Xh paragraphs (%d bytes) -> %04X'
                             % (bx, bx * 16, seg))
            elif ah == 0x49:
                ok = self.heap.pop(es, None) is not None
                self.carry(not ok)
                self.say('21/49 free %04X%s' % (es, '' if ok else ' (BAD)'))
            else:
                self.say('21/%02X ?' % ah)
        else:
            self.say('INT %02Xh AX=%04X ?' % (n, ax))

    def deliver_vsync(self):
        if not self.armed or self.imr & 4 or not self.r('EFLAGS') & 0x200:
            return
        off, seg = struct.unpack('<HH', self.rd(0, 0x28, 4))
        if seg == 0:
            return
        self.armed = False
        self.frame += 1
        sp = (self.r('SP') - 6) & 0xFFFF
        ss = self.r('SS')
        self.wr(ss, sp, struct.pack('<HHH', self.r('IP'), self.r('CS'),
                                    self.r('EFLAGS') & 0xFFFF))
        self.w('SP', sp)
        self.w('EFLAGS', self.r('EFLAGS') & ~0x200)
        self.w('CS', seg)
        self.w('IP', off)

    def call(self, load, args):
        """exec-mem load args...  -> (CH, CL, AX) at return"""
        blk = [len(args)]
        soff = STR_OFF
        for x in args:
            if isinstance(x, bytes):
                self.wr(ISEG, soff, b'"' + x + b'"')
                blk.append(soff)
                soff += len(x) + 3
            else:
                blk.append(x & 0xFFFF)
        self.wr(ISEG, ARG_OFF, struct.pack('<%dH' % len(blk), *blk))
        reg3 = (blk[1:] + [0, 0, 0])[:3]
        for nm, v in zip(('BX', 'DX', 'CX'), reg3):
            self.w(nm, v)
        self.w('DS', ISEG)
        self.w('ES', ISEG)
        self.w('SS', SSEG)
        self.w('SP', 0xFFEE)
        self.wr(SSEG, 0xFFEE, struct.pack('<H', RET_OFF))
        self.w('SI', ARG_OFF)
        self.w('CS', ISEG)
        self.w('IP', load)
        self.w('EFLAGS', 0x202)
        self.blocked = False
        steps = 0
        while not self.blocked:
            cs, ip = self.r('CS'), self.r('IP')
            if (cs, ip) == (ISEG, RET_OFF):
                break
            self.uc.emu_start(cs * 16 + ip, ISEG * 16 + RET_OFF, count=20000)
            self.deliver_vsync()
            steps += 1
            if steps > 100000:
                self.say('gave up (too many instructions)')
                break
        cx = self.r('CX')
        return cx >> 8, cx & 0xFF, self.r('AX')


def parse_arg(s):
    if len(s) >= 2 and s[0] == '"' and s[-1] == '"':
        body = s[1:-1]
        body = re.sub(r'\\x([0-9a-fA-F]{2})',
                      lambda m: chr(0xDC00 + int(m.group(1), 16)), body)
        out = b''
        for ch in body:
            out += bytes([ord(ch) - 0xDC00]) if 0xDC00 <= ord(ch) < 0xDD00 \
                else ch.encode('cp932')
        return out
    return int(s, 0)


def cmd_run(a):
    m = Machine(a)
    data = open(a.file, 'rb').read()
    load = int(a.load, 0)
    m.wr(ISEG, load, data)
    if a.palette:
        m.palette = [int(x, 16) for x in a.palette.split(',')]
    if a.mailbox:
        m.wr(MAILBOX[0], MAILBOX[1], struct.pack(
            '<16H', *[int(x, 16) for x in a.mailbox.split(',')]))
    if a.keys:
        m.keys = [int(x, 16) for x in a.keys.split(',')]
    if a.pattern:
        for pg in (0, 1):
            m.vram[pg][:] = bytes(((i * 7 + (i >> 8) * 13 + pg * 101) ^
                                   (i >> 15) * 0x55) & 0xFF
                                  for i in range(4 * 0x8000))
        m.vram_sync_in()
    calls, cur = [], []
    for x in a.args:
        if x == '/':
            calls.append(cur)
            cur = []
        else:
            cur.append(parse_arg(x))
    calls.append(cur)
    for args in calls:
        shown = ' '.join(('"%s"' % x.decode('cp932', 'replace'))
                         if isinstance(x, bytes) else str(x) for x in args)
        print('== exec-mem %d %s' % (load, shown))
        if a.pattern:
            print('   VRAM crc before: page0 %s page1 %s' % tuple(m.vram_crc()))
        m.log = []
        f0 = m.frame
        ch, cl, ax = m.call(load, args)
        for line in m.log:
            print('  ', line)
        print('   returned CH=%02Xh CL=%02Xh AX=%04Xh; %d VSYNCs elapsed; '
              'INT 0Ah vector %04X:%04X, INT 18h vector %04X:%04X' % (
                  (ch, cl, ax, m.frame - f0) +
                  struct.unpack('<HH', m.rd(0, 0x28, 4))[::-1] +
                  struct.unpack('<HH', m.rd(0, 0x60, 4))[::-1]))
        if a.pattern:
            print('   VRAM crc after:  page0 %s page1 %s' % tuple(m.vram_crc()))
    return m


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    p = sub.add_parser('list')
    p.add_argument('--names', default=os.path.join(
        ROOT, 'docs', 're', 'listing', 'tcm-names.tsv'))
    p.add_argument('--dir', default=None)
    p.add_argument('--out', default=None)
    p.set_defaults(fn=cmd_list)
    p = sub.add_parser('run')
    p.add_argument('file')
    p.add_argument('load')
    p.add_argument('args', nargs='*')
    p.add_argument('--keys')
    p.add_argument('--palette')
    p.add_argument('--mailbox')
    p.add_argument('--pattern', action='store_true')
    p.add_argument('--quiet-ports', action='store_true')
    p.set_defaults(fn=cmd_run)
    a = ap.parse_args()
    a.fn(a)


if __name__ == '__main__':
    main()
